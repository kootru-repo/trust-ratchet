import assert from "node:assert/strict";
import { test } from "node:test";
import { generatedGuides } from "../src/harness/outcomes.ts";
import type { Rule } from "../src/harness/rules.ts";

const RULE: Rule = { id: "no-shell", kind: "ban-api", pattern: "os.system", files: ["src/b/**"], message: "m", fix: "f" };

test("S12: a generated note lists the fixes a folder has needed and the rules in it, and says a program wrote it", () => {
  const day = 86_400;
  const commits = [
    { hash: "h3", time: 300 * day, subject: "fix: crash when the list is empty", files: ["src/a/x.ts", "README.md"] },
    { hash: "h2", time: 200 * day, subject: "add list", files: ["src/a/x.ts"] },
    { hash: "h1", time: 100 * day, subject: "fix typo in docs", files: ["src/b/y.py"] },
  ];
  const notes = generatedGuides({ commits, rules: [RULE], files: ["src/a/x.ts", "src/b/y.py", "src/c/z.ts"] });
  assert.deepEqual(notes.map((n) => n.name), ["generated-src-a.md", "generated-src-b.md"]);
  const [a = { text: "" }, b = { text: "" }] = notes;
  assert.ok(a.text.startsWith("applies: src/a/**\nGenerated by a program"));
  assert.ok(a.text.includes("- 1970-10-28 fix: crash when the list is empty (src/a/x.ts)"));
  assert.ok(b.text.includes("Rules that hold here"));
  assert.ok(b.text.includes("- no-shell: m Fix: f"));
  // A subject that is not a fix (a typo) is not listed, and a folder with neither fixes nor rules gets no note.
  assert.equal(b.text.includes("typo"), false);
});
